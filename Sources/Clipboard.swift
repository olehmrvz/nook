import AppKit

struct ClipItem: Codable, Identifiable, Equatable {
    enum Kind: String, Codable { case text, image, files }
    var id = UUID()
    var kind: Kind
    var text: String?
    var imageFile: String?
    var files: [String]?
    var date = Date()
    var pinned = false
    var sourceApp: String?

    var preview: String {
        switch kind {
        case .text: return (text ?? "").trimmingCharacters(in: .whitespacesAndNewlines)
        case .image: return "Изображение"
        case .files: return (files ?? []).map { ($0 as NSString).lastPathComponent }.joined(separator: ", ")
        }
    }
}

/// Clipboard history. Items marked concealed or transient by password managers are never stored.
final class ClipboardStore: ObservableObject {
    @Published private(set) var items: [ClipItem] = []
    @Published var query = ""
    @Published var selection = 0

    private let maxUnpinned = 300
    private let fileURL = supportDir.appendingPathComponent("clipboard.json")
    private let imagesDir = supportDir.appendingPathComponent("clipboard-images", isDirectory: true)
    private var changeCount = NSPasteboard.general.changeCount
    private var timer: Timer?
    private var ownChange = -1

    private static let ignoredTypes: Set<String> = [
        "org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType", "com.agilebits.onepassword",
        "de.petermaurer.TransientPasteboardType", "com.typeit4me.clipping",
    ]

    var filtered: [ClipItem] {
        let q = query.trimmingCharacters(in: .whitespaces).lowercased()
        let base = items.filter { $0.pinned } + items.filter { !$0.pinned }
        guard !q.isEmpty else { return base }
        return base.filter { $0.preview.lowercased().contains(q) || ($0.sourceApp ?? "").lowercased().contains(q) }
    }

    func start() {
        try? FileManager.default.createDirectory(at: imagesDir, withIntermediateDirectories: true)
        load()
        timer = Timer.scheduledTimer(withTimeInterval: 0.5, repeats: true) { [weak self] _ in self?.poll() }
    }

    private func poll() {
        let pb = NSPasteboard.general
        guard pb.changeCount != changeCount else { return }
        changeCount = pb.changeCount
        guard changeCount != ownChange else { return }
        let types = Set((pb.types ?? []).map(\.rawValue))
        guard types.isDisjoint(with: Self.ignoredTypes) else { return }
        let app = NSWorkspace.shared.frontmostApplication?.localizedName

        if let urls = pb.readObjects(forClasses: [NSURL.self], options: [.urlReadingFileURLsOnly: true]) as? [URL],
           !urls.isEmpty {
            add(ClipItem(kind: .files, files: urls.map(\.path), sourceApp: app))
        } else if let string = pb.string(forType: .string),
                  !string.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty {
            add(ClipItem(kind: .text, text: string, sourceApp: app))
        } else if let image = NSImage(pasteboard: pb), let png = image.pngData {
            let name = UUID().uuidString + ".png"
            try? png.write(to: imagesDir.appendingPathComponent(name))
            add(ClipItem(kind: .image, imageFile: name, sourceApp: app))
        }
    }

    private func add(_ item: ClipItem) {
        var item = item
        if let index = items.firstIndex(where: { $0.kind == item.kind && $0.text == item.text
            && $0.files == item.files && item.kind != .image }) {
            item.pinned = items[index].pinned
            items.remove(at: index)
        }
        items.insert(item, at: 0)
        trim()
        save()
    }

    private func trim() {
        var unpinned = 0
        items.removeAll { item in
            guard !item.pinned else { return false }
            unpinned += 1
            if unpinned > maxUnpinned { deleteImage(of: item); return true }
            return false
        }
    }

    func image(for item: ClipItem) -> NSImage? {
        guard let name = item.imageFile else { return nil }
        return NSImage(contentsOf: imagesDir.appendingPathComponent(name))
    }

    func copyToPasteboard(_ item: ClipItem) {
        let pb = NSPasteboard.general
        pb.clearContents()
        switch item.kind {
        case .text: pb.setString(item.text ?? "", forType: .string)
        case .image: if let image = image(for: item) { pb.writeObjects([image]) }
        case .files: pb.writeObjects((item.files ?? []).map { URL(fileURLWithPath: $0) as NSURL })
        }
        ownChange = pb.changeCount
        // Move the picked entry to the top, like a fresh copy.
        if let index = items.firstIndex(of: item) {
            var moved = items.remove(at: index)
            moved.date = Date()
            items.insert(moved, at: 0)
            save()
        }
    }

    func togglePin(_ item: ClipItem) {
        guard let index = items.firstIndex(where: { $0.id == item.id }) else { return }
        items[index].pinned.toggle()
        save()
    }

    func delete(_ item: ClipItem) {
        deleteImage(of: item)
        items.removeAll { $0.id == item.id }
        save()
    }

    func clearUnpinned() {
        items.filter { !$0.pinned }.forEach(deleteImage)
        items.removeAll { !$0.pinned }
        save()
    }

    private func deleteImage(of item: ClipItem) {
        if let name = item.imageFile { try? FileManager.default.removeItem(at: imagesDir.appendingPathComponent(name)) }
    }

    private func load() {
        guard let data = try? Data(contentsOf: fileURL),
              let decoded = try? JSONDecoder().decode([ClipItem].self, from: data) else { return }
        items = decoded
    }

    private func save() {
        guard let data = try? JSONEncoder().encode(items) else { return }
        try? data.write(to: fileURL, options: [.atomic])
        try? FileManager.default.setAttributes([.posixPermissions: 0o600], ofItemAtPath: fileURL.path)
    }
}

extension NSImage {
    var pngData: Data? {
        guard let tiff = tiffRepresentation, let rep = NSBitmapImageRep(data: tiff) else { return nil }
        return rep.representation(using: .png, properties: [:])
    }
}
